"""divergent-thinker, on call: the fleet's divergent thinking engine, through Control Center.

It proposes ideas and measures how far an idea sits from the obvious one; it never sends, posts or spends, and
what it gives back reaches Krish only as this engine's own proposal behind the strategy wall. It runs through this
engine's own client and bearer (POST /api/growth/engines/makeyourmindup/divergent, control-center#963) and is
dormant until Control Center serves it: every use first reads capabilities, and with `features.divergent` not true
it makes no call and says "not served", never an error. Three uses:

  recovery   At U4 or U5, not held, with nothing else on the runner's report, `diverge` once for three
             unconventional recovery plays (protocol, "If nothing is proposed": at U5 three, each different in
             kind). About 25 model calls and about $1.30 on Control Center's key, one a day per engine. Every spark
             is checked against this engine's walls (no paid reach, nothing in bulk, consent, platform community
             rules) and the copy lint before it can be proposed; the top survivor is the one ask, the other two
             are report notes. On 18 November a live run proposed plays that broke consent and community rules
             while reading well, which is why the check is code, not judgement.
  hooks      Before the weekly mix plan, `score` the planned caption and Note hooks against the live posts this
             engine already holds (`obvious`), namespace growth-makeyourmindup:hooks. Zero model calls: with no
             live posts held there is no score, never a paid consensus. A hook that sits on the obvious one
             (rejected_gravity) or repeats one already live (rejected_archive) is flagged in the plan, never
             dropped.
  record     The measure job records what went live (the posts' published words, links removed) to the same
             namespace, so the next week's hooks are scored against them. Zero model calls.

A refusal (400, 403, 409 held, 429 daily cap, 503 uncalibrated or spend unreadable) is a quiet line, never a failed
run and never retried.
"""
from pathlib import Path
import re

from .control_center import ProtocolError, SLUG, proposal
from .copy_lint import copy_lint_errors
from .core import instant, today
from .packs import SLOP, prose_errors

FEATURE = 'divergent'
NAMESPACE = 'growth-' + SLUG
HOOKS = NAMESPACE + ':hooks'
RECOVERY = NAMESPACE + ':recovery'
PROPOSAL_PREFIX = SLUG + ':divergent:'
URGENT = (4, 5)
SPARKS = 3
MAX_IDEAS, MAX_OBVIOUS, MAX_RECORD = 100, 30, 200
RECORD_DAYS = 3  # the measure job runs daily; three days of posts covers a missed run
FLAGGED = ('rejected_gravity', 'rejected_archive')
LIVE_FILE = Path('.scratch') / 'divergent' / 'live.json'  # the measure job's live words; the mix plan's obvious hooks
NOT_SERVED = 'divergent-thinker: not served (Control Center has not switched features.divergent on); no call made'
# The public North Star line (docs/NORTH_STAR.md), and the 16 November review's finding.
PROBLEM = 'New publication subscribers a week from organic posts and shares, zero paid'
CONTEXT = ('A weekly AI publication for senior commercial leaders. Reach, not polish, is the constraint: the posts '
           'reach too few people. Every play must be organic and honest, prepared for the founder to carry out himself.')
HOOK_PROBLEM = 'A hook that stops a senior commercial leader scrolling past an AI post and makes them want to read on'
# The U5 plays already on his list (docs/plans/2026-11-13-counted-lattice.md), and the reflex every engine reaches for.
CLICHES = ('Warm placements: a cross-post, guest piece or recommendation with publications the founder names',
           'One founder-visible Substack Live co-stream with another publication',
           "The founder's own LinkedIn post for each approved piece, with a tracked link",
           'Post more', 'Post more often')
# The literal words the vendored copy lint refuses (vendor/content-engine/copy-lint): its name rule and eyebrows.
LINT_WORDS = ('Krish', 'breaking', 'just in', 'must read', 'generated by AI', 'AI generated')
# Sent to divergent-thinker's gate, which rejects any idea holding one of these. The copy lint keeps his name out of
# public posts, but a recovery play is a plan for him, where naming him is fine, so his name is not sent.
BANNED_WORDS = tuple(w for w in tuple(SLOP) + LINT_WORDS if w.lower() != 'krish')

# This engine's walls, as words a play cannot carry (AGENTS.md, "The rules that never bend"). A hit holds the
# spark; it is never reworded here.
WALLS = (
    ('paid', 'the North Star counts organic only and this engine has no spend authority',
     re.compile(r"\b(?:paid|boost(?:s|ed|ing)?|ads?|advert\w*|sponsor\w*|buy(?:s|ing)?|bought|giveaways?|prizes?|"
                r"raffles?|gift cards?|bount(?:y|ies)|incentivi[sz]\w*|pay (?:for|people|creators|someone))\b", re.I)),
    ('bulk', 'every ask is written for one named person (rule 5)',
     re.compile(r"\b(?:bulk|mass|blast\w*|auto-?(?:dm|follow|reply|replies|comment)\w*|automated? (?:dms?|messages?|"
                r"outreach|follows?|comments?|repl\w+)|cold dms?|dm (?:every|all|each)\w*|scrap(?:e|es|ed|ing)|"
                r"every (?:follower|subscriber|commenter|member)s?)\b", re.I)),
    ('consent', "nobody is added, tagged, quoted or subscribed without asking, and nobody's words are reused",
     re.compile(r"\b(?:without (?:asking|permission|consent|their)|(?:add|subscribe|enrol|enroll|import|opt) "
                r"(?:them|people|readers|contacts|followers|members)\b|email lists?|their (?:emails?|inbox)|"
                r"contact lists?|tag (?:people|everyone|friends|them)|screenshot\w* (?:their|private|dms?)|"
                r"(?:repost|reuse|share) (?:their|someone'?s?) (?:\w+ )?(?:posts?|images?|photos?|videos?|words))", re.I)),
    ('community', "no pods, swaps for follows, fake accounts or link drops into other people's spaces",
     re.compile(r"\b(?:engagement pods?|follow[- ]?(?:for|4)[- ]?follow|f4f|like[- ]?(?:for|4)[- ]?like|"
                r"sub4sub|sock ?puppets?|fake (?:accounts?|profiles?|reviews?)|(?:second|alt|burner) accounts?|"
                r"astroturf\w*|brigad\w*|upvot\w*|vote rings?|spam\w*|link in every|every (?:group|community|"
                r"subreddit|thread|forum)s?|pose as|pretend\w* to be|impersonat\w*)", re.I)),
)


def served(client):
    """True only when Control Center's capabilities say features.divergent is true. Never raises."""
    if client is None or not hasattr(client, 'divergent'):
        return False
    try:
        features = (client.capabilities() or {}).get('features')
    except ProtocolError:
        return False
    return isinstance(features, dict) and features.get(FEATURE) is True


def refusal(error):
    """The quiet line for a refused or failed call: the server's code when it gave one, else ours."""
    code = getattr(error, 'server_code', None) or getattr(error, 'code', None) or type(error).__name__
    return 'divergent-thinker: not consulted (' + str(code) + '); nothing was retried'


# Recovery plays -------------------------------------------------------------

def spark_text(spark):
    """The play in words, as Krish reads it: what it is, how it works, why it is not obvious, the first step."""
    parts = [('', spark.get('title')), ('How it works: ', spark.get('mechanism')),
             ('Why it is not the obvious play: ', spark.get('whyNonObvious')), ('First step: ', spark.get('firstStep'))]
    return '\n'.join(head + ' '.join(str(words).split()) for head, words in parts
                     if isinstance(words, str) and words.strip())


# "No paid ads" says the wall back, so a play may say it.
NEGATED = re.compile(r"\b(?:no|zero|without|not|never|instead of)\s+(?:\w+\s+)?(?:paid|ads?|boosts?|sponsor\w*)\b", re.I)


def wall_errors(text):
    """Every wall the play's words break, then every lint hit. Empty means it may be proposed."""
    errors = ['wall ' + code + ': ' + why for code, why, rx in WALLS if rx.search(NEGATED.sub(' ', text or ''))]
    errors += prose_errors(text or '')
    try:
        errors += copy_lint_errors(text or '', 'channel_copy')
    except ValueError as exc:  # an unreadable lint config holds the spark, never passes it
        errors.append('copy lint could not run: ' + str(exc))
    return errors


def spark_proposal(spark, run_id, now):
    """The spark as a plan behind strategy, its words the exact payload, its provenance the one evidence item."""
    text = spark_text(spark)
    title = ' '.join(str(spark.get('title') or '').split())
    if not title or not text:
        raise ValueError('a spark needs a title and its words')
    label = 'divergent-thinker spark ' + str(spark.get('rank')) + ', run ' + str(run_id)
    return proposal(PROPOSAL_PREFIX + today(now), 'Recovery play: ' + title,
                    'At U5 nothing else was on the list, so divergent-thinker was asked for three unconventional '
                    'recovery plays, each different in kind; this one cleared the walls and the copy lint. '
                    + ' '.join(str(spark.get('whyNonObvious') or '').split()),
                    'advice', 'strategy', 'plan_approved', exact_payload=text,
                    reference='docs/plans/2026-11-13-counted-lattice.md, the U5 plays', stage='plan',
                    evidence=[{'label': label, 'url': None}])


def waiting(sent):
    """The ids of earlier recovery plays still waiting on Krish (one ask per engine: never a second)."""
    return sorted(pid for pid, state in (sent or {}).items()
                  if isinstance(pid, str) and pid.startswith(PROPOSAL_PREFIX) and state == 'pending')


def recovery(client, directive, gap, sent, now, held=False):
    """(proposal or None, activity lines, holds) for a runner report that otherwise proposes nothing.

    Asks divergent-thinker only at U4 or U5, when this engine is not held, when Krish's ledger was read and no
    earlier play waits on him, and when Control Center serves the route. The caller has already found the report
    empty. Never raises for the route: a refusal is a line."""
    level = (gap or {}).get('urgency')
    if level not in URGENT or held or sent is None or waiting(sent):
        return None, [], []
    if not served(client):
        return None, [NOT_SERVED], []
    current, target = (gap or {}).get('current'), (gap or {}).get('week_target')
    body = {'op': 'diverge', 'problem': PROBLEM, 'count': SPARKS, 'target': 'strategy', 'namespace': RECOVERY,
            'cliches': list(CLICHES), 'bannedWords': list(BANNED_WORDS),
            'context': CONTEXT + (' This week: %s of %s, U%s.' % (current, target, level)
                                  if current is not None and target else '')}
    try:
        answer = client.divergent(body)
    except ProtocolError as error:
        return None, [refusal(error)], []
    run_id = answer.get('runId')
    sparks = [s for s in answer.get('sparks') or [] if isinstance(s, dict)]
    sparks.sort(key=lambda s: s.get('rank') if isinstance(s.get('rank'), int) else 99)
    lines = ['Asked divergent-thinker for ' + str(SPARKS) + ' unconventional recovery plays at U' + str(level)
             + ' (run ' + str(run_id) + ', about 25 model calls on Control Center\'s key): ' + str(len(sparks))
             + ' came back']
    holds, chosen = [], None
    for spark in sparks:
        text = spark_text(spark)
        errors = wall_errors(text)
        if not errors and chosen is None:
            try:
                chosen = spark_proposal(spark, run_id, now)
                continue
            except ValueError as exc:
                errors = [str(exc)]
        if errors:
            holds.append({'reason': 'A divergent-thinker spark broke a wall or the copy lint',
                          'detail': 'spark ' + str(spark.get('rank')) + ', run ' + str(run_id) + ': ' + '; '.join(errors)})
        else:
            # One ask per engine: the next survivors are notes in the report, for Krish to read beside the ask.
            lines.append('Also from divergent-thinker, not asked (one ask at a time): spark ' + str(spark.get('rank'))
                         + ', ' + ' '.join(str(spark.get('title')).split()) + '. First step: '
                         + ' '.join(str(spark.get('firstStep') or 'not given').split()))
    if chosen is None:
        lines.append('No divergent-thinker spark cleared the walls and the copy lint, so none was proposed')
    return chosen, [line[:500] for line in lines], holds


# Hooks before the mix plan --------------------------------------------------

def plan_hooks(mix, ideas=()):
    """[(where, hook)] the plan would carry: each concept's claim (its caption hook) and each idea's planned Note."""
    hooks = []
    for c in mix.get('concepts') or []:
        if isinstance(c.get('claim'), str) and c['claim'].strip():
            hooks.append(('concept ' + str(c.get('concept_id')) + ' caption', ' '.join(c['claim'].split())))
    for idea in ideas or ():
        if isinstance(idea, dict) and isinstance(idea.get('note'), str) and idea['note'].strip():
            hooks.append(('idea ' + str(idea.get('idea_id')) + ' Substack Note', ' '.join(idea['note'].split())))
    return hooks[:MAX_IDEAS]


def guard_hooks(client, mix, ideas=(), live=()):
    """{status, note, flags} for the plan: scored, not_served, unavailable or skipped. Zero model calls."""
    hooks = plan_hooks(mix, ideas)
    live = [w for w in (' '.join(str(x).split()) for x in live or ()) if w][:MAX_OBVIOUS]
    if not hooks:
        return {'status': 'skipped', 'note': 'no caption or Note hook in the plan to score', 'flags': []}
    if not served(client):
        return {'status': 'not_served', 'note': NOT_SERVED, 'flags': []}
    if not live:
        return {'status': 'skipped', 'note': 'no live posts held here (growth.py run measure auto keeps them), so the '
                                             'hooks were not scored: without them a score would spend model calls',
                'flags': []}
    body = {'op': 'score', 'problem': HOOK_PROBLEM, 'ideas': [h for _, h in hooks], 'obvious': live,
            'bannedWords': list(BANNED_WORDS), 'namespace': HOOKS}
    try:
        answer = client.divergent(body)
    except ProtocolError as error:
        return {'status': 'unavailable', 'note': refusal(error), 'flags': []}
    results = answer.get('results') if isinstance(answer.get('results'), list) else []
    flags = []
    for (where, hook), result in zip(hooks, results):
        status = result.get('status') if isinstance(result, dict) else None
        if status in FLAGGED:
            flags.append({'where': where, 'hook': hook, 'status': status,
                          'why': 'sits on the obvious hook' if status == 'rejected_gravity'
                          else 'repeats a hook already live'})
    note = ('scored ' + str(len(hooks)) + ' hooks against ' + str(len(live)) + ' live posts: '
            + str(len(flags)) + ' flagged, none dropped')
    return {'status': 'scored', 'note': note, 'flags': flags,
            'divergence_index': answer.get('divergenceIndex')}


# Recording what went live ----------------------------------------------------

URL = re.compile(r'https?://\S+', re.I)


def live_words(posts, now, days=RECORD_DAYS):
    """The published words of the posts sent in the last `days`, newest first, links removed, each once."""
    cutoff = instant(now).timestamp() - days * 86400
    rows = []
    for post in posts or []:
        try:
            sent = instant(post['sent_at']).timestamp()
        except (KeyError, TypeError, ValueError, AttributeError):
            continue
        words = ' '.join(URL.sub(' ', str(post.get('words') or '')).split())
        if words and sent >= cutoff:
            rows.append((sent, words))
    seen, out = set(), []
    for _, words in sorted(rows, reverse=True):
        if words not in seen:
            seen.add(words)
            out.append(words)
    return out[:MAX_RECORD]


def record_live(client, posts, now):
    """One record call with the live posts' words, when served. Returns a line with counts only, never words."""
    items = live_words(posts, now)
    if not items:
        return None
    if not served(client):
        return NOT_SERVED
    try:
        client.divergent({'op': 'record', 'items': items, 'namespace': HOOKS, 'label': 'live posts to ' + today(now)})
    except ProtocolError as error:
        return refusal(error)
    return 'divergent-thinker: recorded ' + str(len(items)) + ' live posts to ' + HOOKS


# At will: any session in this repository, by hand -----------------------------

# The ops Control Center's route takes, and the ones that spend model calls on its key (a refusal while held).
OPS = ('map', 'provoke', 'challenge', 'diverge', 'score', 'record')
GENERATING = ('map', 'provoke', 'challenge', 'diverge')
COST = {'map': '1 model call', 'provoke': '2 model calls, about $0.15', 'challenge': '3 model calls',
        'diverge': 'about 25 model calls and about $1.30, one a day', 'score': 'no model call with obvious hooks',
        'record': 'no model call'}
LANE = re.compile(r'^[a-z0-9][a-z0-9_-]{0,39}$')
EXIT_OK, EXIT_FLAGGED, EXIT_UNAVAILABLE = 0, 1, 2


def items_of(path):
    """A JSON list of strings, or one item a line. Blank lines and blank items are dropped."""
    import json
    text = Path(path).read_text(encoding='utf-8-sig')
    try:
        value = json.loads(text)
    except ValueError:
        value = None
    rows = value if isinstance(value, list) else text.splitlines()
    return [w for w in (' '.join(str(x).split()) for x in rows) if w]


def at_will_body(op, problem=None, context=None, idea=None, ideas=(), obvious=(), items=(), cliches=(),
                 count=None, target=None, temperament=None, lane=None, judge=False, label=None):
    """The exact body Control Center's route takes for one at-will op. Raises ValueError on a missing input."""
    if op not in OPS:
        raise ValueError('op must be one of ' + ', '.join(OPS))
    if lane is not None and not LANE.match(lane):
        raise ValueError('--lane is lower case letters, digits, - and _ (at most 40)')
    namespace = NAMESPACE + (':' + lane if lane else '')
    if op == 'record':
        if not items:
            raise ValueError('record needs --items-file with at least one item')
        body = {'op': op, 'items': list(items)[:MAX_RECORD], 'namespace': namespace}
        if label:
            body['label'] = label
        return body
    if not (problem or '').strip():
        raise ValueError(op + ' needs --problem')
    body = {'op': op, 'problem': ' '.join(problem.split())}
    if op == 'score':
        if not ideas:
            raise ValueError('score needs --ideas-file with at least one idea')
        body.update(ideas=list(ideas)[:MAX_IDEAS], bannedWords=list(BANNED_WORDS), namespace=namespace)
        if obvious:
            body['obvious'] = list(obvious)[:MAX_OBVIOUS]
        if judge:
            body['judge'] = True
        return body
    if context:
        body['context'] = ' '.join(context.split())
    if op == 'map':
        return body
    if op == 'challenge':
        if not (idea or '').strip():
            raise ValueError('challenge needs --idea')
        body['idea'] = ' '.join(idea.split())
        return body
    # provoke and diverge
    body.update(bannedWords=list(BANNED_WORDS), namespace=namespace)
    if cliches:
        body['cliches'] = [' '.join(c.split()) for c in cliches if c.strip()]
    if count is not None:
        body['count'] = count
    if target:
        body['target'] = target
    if temperament:
        body['temperament'] = temperament
    return body


def flagged(answer):
    """The score results divergent-thinker rejected (any rejected_* status)."""
    results = answer.get('results') if isinstance(answer.get('results'), list) else []
    return [r for r in results if isinstance(r, dict) and str(r.get('status') or '').startswith('rejected')]


def at_will(client, body):
    """(exit code, answer or None, reason or None). One call at most, never retried, never written to his list.

    Not served, unreachable, a refusal, or a held engine for a generating op is exit 2 with its reason and no
    divergent call; a score that rejects anything is exit 1."""
    if not served(client):
        return EXIT_UNAVAILABLE, None, NOT_SERVED
    if body['op'] in GENERATING:
        from .engine_state import held
        try:
            directive = client.directive()
        except (ProtocolError, AttributeError):
            return EXIT_UNAVAILABLE, None, ('divergent-thinker: not consulted (held state unreadable); a generating '
                                            'op spends model calls, so none was made')
        if held(directive):
            return EXIT_UNAVAILABLE, None, ('divergent-thinker: not consulted (held); Control Center holds this '
                                            'engine, so no generating op runs')
    try:
        answer = client.divergent(body)
    except ProtocolError as error:
        return EXIT_UNAVAILABLE, None, refusal(error)
    if body['op'] == 'score' and flagged(answer):
        return EXIT_FLAGGED, answer, None
    return EXIT_OK, answer, None


def command(argv, client_factory):
    """growth.py divergent <op> [options]: print Control Center's JSON. Exit 0 ok, 1 a score flagged something,
    2 not served, unreachable, refused or held (the reason on stderr)."""
    import argparse
    import json
    import sys
    p = argparse.ArgumentParser(prog='growth.py divergent',
                                description='divergent-thinker at will, through Control Center (engine/divergent.py)',
                                epilog='Cost: ' + '; '.join(op + ' ' + COST[op] for op in OPS) + '.')
    p.add_argument('op', choices=OPS)
    p.add_argument('--problem'); p.add_argument('--context'); p.add_argument('--idea')
    p.add_argument('--ideas-file'); p.add_argument('--obvious-file'); p.add_argument('--items-file')
    p.add_argument('--label', help='record: a short label for the batch')
    p.add_argument('--cliche', action='append', default=[])
    p.add_argument('--count', type=int); p.add_argument('--target'); p.add_argument('--temperament')
    p.add_argument('--lane', help='namespace ' + NAMESPACE + ':<lane>')
    p.add_argument('--judge', action='store_true', help='score: ask the judge too (spends model calls)')
    a = p.parse_args(argv)
    try:
        body = at_will_body(a.op, a.problem, a.context, a.idea,
                            items_of(a.ideas_file) if a.ideas_file else (),
                            items_of(a.obvious_file) if a.obvious_file else (),
                            items_of(a.items_file) if a.items_file else (),
                            a.cliche, a.count, a.target, a.temperament, a.lane, a.judge, a.label)
    except (ValueError, OSError) as error:
        p.error(str(error))
    try:
        client = client_factory()
    except ValueError as error:
        print('divergent-thinker: not consulted (' + str(error) + ')', file=sys.stderr)
        return EXIT_UNAVAILABLE
    code, answer, reason = at_will(client, body)
    if reason:
        print(reason, file=sys.stderr)
    if answer is not None:
        print(json.dumps(answer, ensure_ascii=False, indent=2))
    return code
