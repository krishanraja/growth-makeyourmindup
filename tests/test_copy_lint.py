"""The vendored copy lint: content-engine's patterns, run here unchanged.

Krish, 2026-10-28: "don't add stupid eyebrow text and asterisks and "generated
by AI" and "Krish's take" verbal diahorrea like you tend to. This needs to feel
like a world class media channel".

Offline only; synthetic and approved copy, no network.
"""
import hashlib
import json
from pathlib import Path
import re
import tempfile
import unittest

from engine import copy_lint

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'vendor' / 'content-engine' / 'copy-lint'
NAMED_SURFACES = ('channel_copy', 'article_metadata', 'carousel_text')


class CopyLintTests(unittest.TestCase):
    def test_vendored_config_is_the_pinned_upstream_file(self):
        source = (VENDOR / 'SOURCE.md').read_text(encoding='utf-8')
        data = (VENDOR / 'copy-lint.json').read_bytes()
        self.assertIn('- sha256: `' + hashlib.sha256(data).hexdigest() + '`', source)
        version = json.loads(data.decode('utf-8'))['version']
        self.assertIn('- Version: `' + version + '`', source)
        self.assertEqual(copy_lint.version(), version)
        self.assertRegex(re.search(r'Commit: `([0-9a-f]+)`', source).group(1), r'^[0-9a-f]{40}$')

    def test_every_pattern_krish_named_is_refused_where_he_named_it(self):
        named = {
            'eyebrow_label': ('BREAKING: Disney is hiring the team', 'AI NEWS', 'Pro tip: ask for the end date'),
            'asterisk': ('The *real* cost is the lock-in', 'Prices fell by half*'),
            'ai_provenance_label': ('Generated by AI', 'Disney hires the team. (AI-generated)'),
            'ai_self_note': ('This video was made with Runway.',),
            'ai_illustration_note': ('The illustrations were generated with AI.',),
            'ai_credit_line': ('Visuals by Midjourney',),
            'take_label': ("Krish's take: the money moved to the chips", 'My take: watch the lawyers',
                           "Krish's read: the money moved to the chips"),
            # Krish, 28 Oct 2026: the labels "Krish's read" or "illustrative" "add no value to the content".
            'illustration_label': ('ILLUSTRATIVE', '(illustrative)', '[Illustrative]', 'Illustrative'),
        }
        for pattern, examples in named.items():
            for text in examples:
                for surface in NAMED_SURFACES:
                    ids = [h['id'] for h in copy_lint.copy_lint(text, surface)]
                    self.assertIn(pattern, ids, (text, surface))
                    self.assertTrue(copy_lint.copy_lint_errors(text, surface), (text, surface))

    def test_approved_copy_and_ai_as_the_subject_pass(self):
        # Monday 26 October (follow.the.money): the title and card lines Krish approved.
        approved = ('Why is Disney eating the scraps of bankrupt Character.AI?',
                    "Google paid $2.7 billion for Character.AI's tech and founders",
                    "Disney rented space in OpenAI's Sora app",
                    "Disney leaves Character.AI's users and lawsuits behind",
                    'Skydance, Universal and Comcast: who buys AI next')
        topics = ('AI-generated music changes who gets paid.',
                  'Read it at makeyourmindup.ai/follow_the_money',
                  'Who signs the cheque when the model is wrong?')
        for text in approved + topics:
            for surface in NAMED_SURFACES + ('titles', 'video_onscreen'):
                self.assertEqual(copy_lint.copy_lint(text, surface), [], (text, surface))

    def test_his_name_is_refused_on_every_public_surface_the_article_body_too(self):
        # Krish, 2026-10-28: "Remember, no content refers to Krish, ever. I still see that popping up
        # from time to time. Even articles written are not authored by Krish. My face only, for assets
        # and the video format." Asked whether another Krish may be named, he picked "Yes, block it".
        self.assertEqual(copy_lint.SURFACES, ('channel_copy', 'carousel_text', 'video_onscreen', 'titles',
                                              'article_metadata', 'article_body'))
        for text in ('By Krish Raja', "Krish's test of the chip money", 'Follow @TheRealKrisho',
                     'More at krishraja.com', 'KRISH', 'krish_raja1 on Threads', 'Krishan Raja wrote this'):
            for surface in copy_lint.SURFACES:
                self.assertIn('no_name', [h['id'] for h in copy_lint.copy_lint(text, surface)], (text, surface))
        # The publication speaks as "we"; his personal posts may say "I". Neither names him.
        for text in ('We tested it on the chip money.', 'I ran the test myself.', 'Our test: the chip money.'):
            for surface in copy_lint.SURFACES:
                self.assertNotIn('no_name', [h['id'] for h in copy_lint.copy_lint(text, surface)], (text, surface))

    def test_markdown_that_prints_raw_on_a_social_post_is_refused(self):
        # Krish, 2026-11-01: "we cannot risk crappy formatting". A list line stays allowed.
        for text, pattern in (('## THE BIT\nWords.', 'markdown_heading'), ('Read [this](https://x.ai)', 'markdown_link'),
                              ('> A quote\nWords.', 'markdown_quote'), ('Run `this` weekly.', 'backtick')):
            self.assertIn(pattern, [h['id'] for h in copy_lint.copy_lint(text, 'channel_copy')], text)
        self.assertEqual(copy_lint.copy_lint('Three things:\n- Name your seniors.\n- Check your hires.', 'channel_copy'), [])

    def test_only_the_name_rule_reads_the_article_body(self):
        # The body's markdown emphasis and headings are the markdown itself, so no other pattern reads it.
        body = '## BREAKING: the money\n\nThe *real* cost is the lock-in. My take: watch the lawyers.'
        self.assertEqual(copy_lint.copy_lint(body, 'article_body'), [])
        self.assertEqual([h['id'] for h in copy_lint.copy_lint(body + ' Krish says so.', 'article_body')],
                         ['no_name'])

    def test_odd_spaces_and_line_ends_are_read_as_content_engine_reads_them(self):
        self.assertEqual([h['id'] for h in copy_lint.copy_lint('Hot take: no', 'channel_copy')], ['take_label'])
        hit = copy_lint.copy_lint('First line.\r\nMy take: second', 'channel_copy')[0]
        self.assertEqual((hit['id'], hit['line']), ('take_label', 2))
        # content-engine's reader turns U+2028, U+2029 and U+0085 into line ends too (_LINE_ENDS at the
        # pinned commit), so an eyebrow that opens the second line is refused here as it is there.
        for end in ('\u2028', '\u2029', '\u0085'):
            hits = copy_lint.copy_lint('Intro line' + end + 'BREAKING: OpenAI ships', 'channel_copy')
            self.assertEqual([(h['id'], h['line']) for h in hits], [('eyebrow_label', 2)], repr(end))
        self.assertEqual([h['id'] for h in copy_lint.copy_lint('My\u00a0take: second', 'channel_copy')], ['take_label'])

    def test_known_upstream_refusals_are_listed_as_they_stand(self):
        # SOURCE.md lists true third-party reporting this version refuses, for content-engine to fix.
        # When a re-vendored version stops refusing one, this fails and the row comes out.
        source = (VENDOR / 'SOURCE.md').read_text(encoding='utf-8').split('## Known refusals to send upstream', 1)[1]
        rows = re.findall(r'^\| (.+?) \| `([a-z_]+)` \|$', source, re.M)
        self.assertEqual(len(rows), 5)
        for sentence, pattern in rows:
            self.assertIn(pattern, [h['id'] for h in copy_lint.copy_lint(sentence, 'channel_copy')], sentence)

    def test_unknown_surface_and_broken_config_refuse(self):
        with self.assertRaisesRegex(ValueError, 'applies_to must be one of'):
            copy_lint.copy_lint('Plain words.', 'somewhere_else')
        with tempfile.TemporaryDirectory() as tmp:
            bad = Path(tmp) / 'copy-lint.json'
            for body in ('not json', json.dumps({'version': '1', 'patterns': []}),
                         json.dumps({'version': '1', 'patterns': [{'id': 'x', 'regex': 'a', 'flags': 'g',
                                                                    'applies_to': ['channel_copy']}]}),
                         json.dumps({'version': '1', 'patterns': [{'id': 'x', 'regex': 'a', 'flags': '',
                                                                    'applies_to': ['nowhere']}]})):
                bad.write_text(body, encoding='utf-8')
                copy_lint._cache.pop(str(bad), None)
                with self.assertRaises(ValueError):
                    copy_lint.copy_lint('Plain words.', 'channel_copy', bad)


if __name__ == '__main__':
    unittest.main()
